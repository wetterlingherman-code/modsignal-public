export function normalizeModerationData(payload) {
  const data = payload?.comments?.length ? payload : fallbackModerationData;
  const normalizedComments = data.comments.map((comment, index) => ({
    ...comment,
    id: comment.id || `case-${index}`,
    user: comment.user || comment.username || `reader_${index}`,
    username: comment.username || comment.user || `reader_${index}`,
    text: comment.text || comment.comment_text || '',
    comment_text: comment.comment_text || comment.text || '',
    flag: comment.flag ?? comment.risk_level ?? null,
    risk_level: comment.risk_level ?? comment.flag ?? null,
    risk: comment.risk ?? comment.risk_score ?? 0,
    status: comment.status || (comment.flag || comment.risk_level ? 'open' : 'background'),
    tags: comment.tags || [],
    reports: comment.reports || 0,
    depth: Math.min(comment.depth || 0, 3),
    branchId: comment.branchId || 'general',
    avatarHue: comment.avatarHue || 180,
    age: comment.age || 'now',
    votes: comment.votes || 0,
    karma: comment.karma || '1.0k',
    risk_signals: comment.risk_signals || ['Derived prototype signal.'],
    suggested_action: comment.suggested_action || 'review context',
    toxicity_score: comment.toxicity_score || 0,
    escalation_score: comment.escalation_score || 0,
    tone: comment.tone || 'neutral',
  }));

  return {
    ...data,
    thread: {
      ...fallbackModerationData.thread,
      ...data.thread,
      commentCount: normalizedComments.length,
    },
    overview: {
      ...fallbackModerationData.overview,
      ...data.overview,
    },
    comments: normalizedComments,
  };
}

export function getPriorityQueue(commentList = comments) {
  return [...commentList]
    .filter((comment) => comment.flag && comment.status !== 'resolved')
    .sort((a, b) => b.risk - a.risk);
}
